"""Project N.O.M.A.D. (offline knowledge server) as an optional companion: ``duckops nomad up|down|status|logs|url``.

It never runs unless asked. Secrets are generated on the first ``up`` and kept in ``~/.duckclaw/project-nomad/.env`` (mode 0600); data lives next to it.
The compose file is deploy/optional/project-nomad/docker-compose.yml (adapted from the Apache-2.0 upstream template; read its header for the differences and the Docker socket warning).
"""

from __future__ import annotations

import os
import secrets
import shutil
import subprocess
import time
import urllib.request
from pathlib import Path

import typer

app = typer.Typer(help="Project N.O.M.A.D. opcional: servidor offline con Wikipedia, libros, mapas y IA local (no forma parte del stack por defecto).")

_LOOPBACK = {"127.0.0.1", "localhost", "::1"}


def _repo_root() -> Path:
    return Path(__file__).resolve().parent.parent.parent.parent.parent


def compose_file() -> Path:
    return _repo_root() / "deploy" / "optional" / "project-nomad" / "docker-compose.yml"


def home_dir() -> Path:
    return Path(os.environ.get("DUCKCLAW_NOMAD_HOME") or Path.home() / ".duckclaw" / "project-nomad").expanduser()


def read_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.strip() and not line.startswith("#") and "=" in line:
                k, _, v = line.partition("=")
                out[k.strip()] = v.strip()
    return out


def ensure_env(home: Path, bind: str, port: int) -> dict[str, str]:
    """Create ``.env`` with fresh random secrets when missing; keep every existing value (changing a DB password later would lock the database)."""
    home.mkdir(parents=True, exist_ok=True)
    env_path = home / ".env"
    env = read_env(env_path)
    defaults = {
        "NOMAD_DATA_DIR": str(home / "data"),
        "NOMAD_APP_KEY": secrets.token_urlsafe(32),
        "NOMAD_DB_PASSWORD": secrets.token_urlsafe(24),
        "NOMAD_DB_ROOT_PASSWORD": secrets.token_urlsafe(24),
        "NOMAD_BIND": bind,
        "NOMAD_PORT": str(port),
        "NOMAD_URL": f"http://127.0.0.1:{port}" if bind in _LOOPBACK else f"http://{bind}:{port}",
    }
    changed = False
    for k, v in defaults.items():
        if k not in env:
            env[k], changed = v, True
    if changed:
        env_path.write_text("# Generated by `duckops nomad up`. Keep it private; do not change the DB passwords once the database exists.\n" + "".join(f"{k}={v}\n" for k, v in env.items()), encoding="utf-8")
        try:
            env_path.chmod(0o600)
        except OSError:
            pass
    Path(env["NOMAD_DATA_DIR"]).mkdir(parents=True, exist_ok=True)
    return env


def compose_argv(home: Path, *args: str) -> list[str]:
    return ["docker", "compose", "-f", str(compose_file()), "--env-file", str(home / ".env"), "--project-directory", str(home), *args]


def _need_docker() -> None:
    if shutil.which("docker") is None:
        typer.echo("Docker no está instalado o no está en el PATH. Instálalo primero: https://docs.docker.com/get-docker/", err=True)
        raise typer.Exit(2)


def _run(argv: list[str], dry_run: bool) -> int:
    if dry_run:
        typer.echo("[dry-run] " + " ".join(argv))
        return 0
    return subprocess.call(argv)


@app.command("up")
def up(
    bind: str = typer.Option("127.0.0.1", "--bind", help="Interfaz donde publica el panel. Por defecto solo loopback."),
    port: int = typer.Option(8080, "--port", help="Puerto del panel en el host."),
    expose: bool = typer.Option(False, "--expose", help="Permite --bind distinto de loopback (el panel controla el Docker del host: solo en redes privadas)."),
    wait: int = typer.Option(120, "--wait", help="Segundos que espera a que el panel responda."),
    dry_run: bool = typer.Option(False, "--dry-run", help="Muestra los comandos sin ejecutarlos ni escribir archivos."),
) -> None:
    """Levanta NOMAD (descarga imágenes la primera vez; sin IA ocupa menos de 1 GB de RAM y unos 5 GB de disco)."""
    if bind not in _LOOPBACK and not expose:
        typer.echo(f"--bind {bind} publicaría el panel fuera de este equipo. NOMAD monta el socket de Docker del host: añade --expose solo si es una red privada.", err=True)
        raise typer.Exit(2)
    home = home_dir()
    if dry_run:
        typer.echo(f"[dry-run] se crearía {home / '.env'} con secretos aleatorios (0600) y datos en {home / 'data'}")
        raise typer.Exit(_run(compose_argv(home, "up", "-d"), True))
    _need_docker()
    env = ensure_env(home, bind, port)
    code = _run(compose_argv(home, "up", "-d"), False)
    if code:
        raise typer.Exit(code)
    url = f"http://127.0.0.1:{env['NOMAD_PORT']}"
    deadline = time.time() + wait
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(f"{url}/api/health", timeout=5):  # noqa: S310 (local panel)
                typer.echo(f"NOMAD listo: {url}  (datos en {env['NOMAD_DATA_DIR']})")
                typer.echo("Aviso: el panel controla el Docker de este equipo. No lo expongas a internet.")
                return
        except Exception:  # noqa: BLE001
            time.sleep(3)
    typer.echo(f"NOMAD arrancó pero {url}/api/health aún no responde; mira `uv run duckops nomad logs`.", err=True)
    raise typer.Exit(1)


@app.command("down")
def down(dry_run: bool = typer.Option(False, "--dry-run")) -> None:
    """Detiene NOMAD. Los datos y los secretos se conservan."""
    if not dry_run:
        _need_docker()
    raise typer.Exit(_run(compose_argv(home_dir(), "down"), dry_run))


@app.command("status")
def status(dry_run: bool = typer.Option(False, "--dry-run")) -> None:
    """Estado de los contenedores de NOMAD."""
    if not dry_run:
        _need_docker()
    raise typer.Exit(_run(compose_argv(home_dir(), "ps"), dry_run))


@app.command("logs")
def logs(tail: int = typer.Option(100, "--tail"), dry_run: bool = typer.Option(False, "--dry-run")) -> None:
    """Últimas líneas de log (el visor Dozzle de upstream no se instala)."""
    if not dry_run:
        _need_docker()
    raise typer.Exit(_run(compose_argv(home_dir(), "logs", "--tail", str(tail)), dry_run))


@app.command("url")
def url() -> None:
    """Dirección del panel según la configuración guardada."""
    env = read_env(home_dir() / ".env")
    typer.echo(env.get("NOMAD_URL", "NOMAD no está configurado: ejecuta `uv run duckops nomad up`"))
